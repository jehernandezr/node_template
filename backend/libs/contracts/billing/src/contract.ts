import {
  defineServiceContract,
  defineTenantMoveOperations,
} from '@contracts/platform';
import {
  BillingLimits,
  UsageAggregation,
} from './constants/billing.constants.js';
import {
  Currency,
  InvoiceLineKind,
  InvoiceStatus,
  PlanPeriodicity,
  SubscriptionStatus,
  UsageAggregationKind,
  UsageMetric,
} from './enums/billing.enum.js';
import {
  BillingCommand,
  BillingErrorCode,
  BillingEvent,
  BillingOperation,
  BillingQueue,
  BillingRoute,
  BillingTopic,
} from './enums/identifiers.enum.js';
import { billingErrorCatalog } from './errors/billing-error-catalog.js';
import {
  BillingEventsTopic,
  EntitlementsChangedEvent,
  IdentityEventsQueue,
  InvoiceFailedEvent,
  InvoiceIssuedEvent,
  InvoicePaidEvent,
  RecordUsageCommand,
  SubscriptionChangedEvent,
  SubscriptionReactivatedEvent,
  SubscriptionSuspendedEvent,
  UsageQueue,
} from './events/index.js';
import {
  ChangePlanRoute,
  GetInvoiceRoute,
  GetSubscriptionRoute,
  GetUsageRoute,
  ListInvoicesRoute,
  ListPlansRoute,
} from './http/billing.routes.js';
import {
  CheckQuotaOperation,
  CloseAccountOperation,
  GetEntitlementsOperation,
  MarkInvoiceFailedOperation,
  MarkInvoicePaidOperation,
  OpenAccountOperation,
} from './internal/billing.operations.js';
import * as schemas from './schemas/index.js';

const tenantMove = defineTenantMoveOperations('billing');

/** Contrato del servicio billing: planes, suscripciones, uso, facturas, cuotas y eventos. */
export const billingContract = defineServiceContract({
  service: 'billing',
  description:
    'Facturación: planes, suscripción del tenant, medición de uso, entitlements, cuotas, facturas y morosidad.',
  enums: {
    SubscriptionStatus,
    InvoiceStatus,
    InvoiceLineKind,
    PlanPeriodicity,
    Currency,
    UsageMetric,
    UsageAggregationKind,
    BillingErrorCode,
    BillingRoute,
    BillingOperation,
    BillingEvent,
    BillingCommand,
    BillingTopic,
    BillingQueue,
  },
  constants: { BillingLimits, UsageAggregation },
  schemas: {
    UsageMetric: schemas.UsageMetricSchema,
    SubscriptionStatus: schemas.SubscriptionStatusSchema,
    InvoiceStatus: schemas.InvoiceStatusSchema,
    InvoiceLineKind: schemas.InvoiceLineKindSchema,
    PlanPeriodicity: schemas.PlanPeriodicitySchema,
    Currency: schemas.CurrencySchema,
    BillingPeriod: schemas.BillingPeriodSchema,
    QuotaLimit: schemas.QuotaLimitSchema,
    UsageRecord: schemas.UsageRecordSchema,
    RecordUsagePayload: schemas.RecordUsagePayloadSchema,
    SubscriptionChangedPayload: schemas.SubscriptionChangedPayloadSchema,
    SubscriptionSuspendedPayload: schemas.SubscriptionSuspendedPayloadSchema,
    SubscriptionReactivatedPayload:
      schemas.SubscriptionReactivatedPayloadSchema,
    EntitlementsChangedPayload: schemas.EntitlementsChangedPayloadSchema,
    InvoiceIssuedPayload: schemas.InvoiceIssuedPayloadSchema,
    InvoicePaidPayload: schemas.InvoicePaidPayloadSchema,
    InvoiceFailedPayload: schemas.InvoiceFailedPayloadSchema,
    Plan: schemas.PlanSchema,
    PlanCatalog: schemas.PlanCatalogSchema,
    Subscription: schemas.SubscriptionSchema,
    QuotaUsage: schemas.QuotaUsageSchema,
    UsageOverview: schemas.UsageOverviewSchema,
    InvoiceLine: schemas.InvoiceLineSchema,
    Invoice: schemas.InvoiceSchema,
    InvoiceSummary: schemas.InvoiceSummarySchema,
    InvoicePage: schemas.InvoicePageSchema,
    ChangePlanRequest: schemas.ChangePlanRequestSchema,
    ListInvoicesRequest: schemas.ListInvoicesRequestSchema,
    GetInvoiceRequest: schemas.GetInvoiceRequestSchema,
    OpenBillingAccountInput: schemas.OpenBillingAccountInputSchema,
    BillingAccountResult: schemas.BillingAccountResultSchema,
    CloseBillingAccountInput: schemas.CloseBillingAccountInputSchema,
    BillingAccountClosed: schemas.BillingAccountClosedSchema,
    GetEntitlementsInput: schemas.GetEntitlementsInputSchema,
    Entitlements: schemas.EntitlementsSchema,
    CheckQuotaInput: schemas.CheckQuotaInputSchema,
    QuotaCheck: schemas.QuotaCheckSchema,
    MarkInvoicePaidInput: schemas.MarkInvoicePaidInputSchema,
    MarkInvoiceFailedInput: schemas.MarkInvoiceFailedInputSchema,
    InvoiceStateResult: schemas.InvoiceStateResultSchema,
  },
  routes: {
    getSubscription: GetSubscriptionRoute,
    getUsage: GetUsageRoute,
    listPlans: ListPlansRoute,
    changePlan: ChangePlanRoute,
    listInvoices: ListInvoicesRoute,
    getInvoice: GetInvoiceRoute,
  },
  operations: {
    openAccount: OpenAccountOperation,
    closeAccount: CloseAccountOperation,
    getEntitlements: GetEntitlementsOperation,
    checkQuota: CheckQuotaOperation,
    markInvoicePaid: MarkInvoicePaidOperation,
    markInvoiceFailed: MarkInvoiceFailedOperation,
    tenantMoveSync: tenantMove.tenantMoveSync,
    tenantMoveFinalize: tenantMove.tenantMoveFinalize,
    tenantMoveAbort: tenantMove.tenantMoveAbort,
    tenantMoveCleanup: tenantMove.tenantMoveCleanup,
  },
  events: {
    subscriptionChanged: SubscriptionChangedEvent,
    subscriptionSuspended: SubscriptionSuspendedEvent,
    subscriptionReactivated: SubscriptionReactivatedEvent,
    entitlementsChanged: EntitlementsChangedEvent,
    invoiceIssued: InvoiceIssuedEvent,
    invoicePaid: InvoicePaidEvent,
    invoiceFailed: InvoiceFailedEvent,
  },
  commands: { recordUsage: RecordUsageCommand },
  topics: { events: BillingEventsTopic },
  queues: { usage: UsageQueue, identityEvents: IdentityEventsQueue },
  errors: { BillingErrorCode: billingErrorCatalog },
});
