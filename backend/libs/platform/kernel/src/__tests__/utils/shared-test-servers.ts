import type { SharedPostgres } from './shared-postgres.js';
import { SharedServerVariable } from './shared-server-variable.enum.js';
import type { SharedValkey } from './shared-valkey.js';

/**
 * Reads the PostgreSQL and the Valkey that the Jest `globalSetup` started for every integration suite of the run.
 * Each suite creates its own databases, roles and Valkey users on them instead of starting its own containers.
 */
export class SharedTestServers {
  private static readonly ADMIN_DATABASE = 'postgres';

  constructor(
    private readonly env: Readonly<Record<string, string | undefined>>,
  ) {}

  /**
   * The shared PostgreSQL.
   * @returns Its address and superuser.
   * @throws Error when the run did not go through the Jest preset that starts the servers.
   */
  postgres(): SharedPostgres {
    return {
      host: this.required(SharedServerVariable.PostgresHost),
      port: Number(this.required(SharedServerVariable.PostgresPort)),
      username: this.required(SharedServerVariable.PostgresUser),
      password: this.required(SharedServerVariable.PostgresPassword),
      adminDatabase: SharedTestServers.ADMIN_DATABASE,
    };
  }

  /**
   * The shared Valkey.
   * @returns Its address.
   * @throws Error when the run did not go through the Jest preset that starts the servers.
   */
  valkey(): SharedValkey {
    return {
      host: this.required(SharedServerVariable.ValkeyHost),
      port: Number(this.required(SharedServerVariable.ValkeyPort)),
    };
  }

  /**
   * Password every service role of the run logs in with, so a role created by one suite serves the next one and
   * the databases cloned from a template keep a valid owner.
   * @returns The password generated by the `globalSetup`.
   * @throws Error when the run did not go through the Jest preset that starts the servers.
   */
  rolePassword(): string {
    return this.required(SharedServerVariable.RolePassword);
  }

  private required(variable: SharedServerVariable): string {
    const value = this.env[variable];
    if (value === undefined || value === '') {
      throw new Error(
        `${variable} is not set: run the suite through the backend Jest preset (nx test-int), which starts the shared test servers`,
      );
    }
    return value;
  }
}
