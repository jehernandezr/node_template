import {
  DEAD_LETTER_SUFFIX,
  MessageKind,
  type QueueDefinition,
  type ServiceContract,
  type TopicDefinition,
} from '@contracts/platform';
import { TOPOLOGY_FORMAT_VERSION } from './export-constants.js';
import { ExportError } from './export-error.js';
import type { GlobalUniquenessChecker } from './global-uniqueness-checker.js';
import type { JsonObject } from './json.type.js';

const SECONDS_PER_DAY = 86_400;

/** Target kind of a route; matches `TargetKind` from `@platform/messaging`. */
enum TargetKind {
  Topic = 'topic',
  Queue = 'queue',
}

interface Owned<T> {
  readonly service: string;
  readonly value: T;
}

/**
 * Global indexes: which service declares each topic (by name), queue and command
 * (by type). It is indexed by name and not by object because a contract that
 * cannot import the owner points to it with `defineTopicReference` and
 * `defineCommandReference`.
 */
interface ContractIndex {
  readonly topics: Map<string, Owned<TopicDefinition>>;
  readonly queues: Owned<QueueDefinition>[];
  readonly commands: Map<string, string>;
}

/**
 * Builds the messaging topology from the contracts: topics with their
 * producers, queues with their consumer, subscriptions with type filters and
 * the route of each event and command. It is the input of the Terraform
 * `messaging` module and the LocalStack script.
 */
export class TopologyBuilder {
  constructor(private readonly uniqueness: GlobalUniquenessChecker) {}

  /**
   * The format extends that of `Topology.toJSON()` from `@platform/messaging` with
   * `owner`, `producers`, `consumer` and `retry`, to derive IAM permissions.
   */
  build(contracts: readonly ServiceContract[]): JsonObject {
    this.uniqueness.check(contracts);
    const index = this.indexContracts(contracts);
    const senders = this.sendersOf(contracts, index);
    const topics = [...index.topics.values()]
      .sort((a, b) => this.byName(a.value, b.value))
      .map((owned) => this.topicOf(owned));
    const queues = [...index.queues]
      .sort((a, b) => this.byName(a.value, b.value))
      .map((owned) => this.queueOf(owned, index, senders));
    return {
      $comment:
        'GENERATED by backend/tools/contracts-export from the contracts. Do not edit: run pnpm nx run contracts-export:topology-export.',
      formatVersion: TOPOLOGY_FORMAT_VERSION,
      topics,
      queues,
      routes: this.routesOf(index),
    };
  }

  /** Route of each event to its topic and of each command to its queue, by type. */
  private routesOf(index: ContractIndex): JsonObject[] {
    const toTopics = [...index.topics.values()].flatMap(
      ({ service, value: topic }) =>
        topic.events.map((event) => ({
          type: event.type,
          kind: MessageKind.Event,
          target: topic.name,
          targetKind: TargetKind.Topic,
          owner: service,
        })),
    );
    const toQueues = index.queues.flatMap(({ service, value: queue }) =>
      queue.commands.map((command) => ({
        type: command.type,
        kind: MessageKind.Command,
        target: queue.name,
        targetKind: TargetKind.Queue,
        owner: service,
      })),
    );
    return [...toTopics, ...toQueues].sort((a, b) =>
      this.compare(a.type, b.type),
    );
  }

  /** Services that send each command; sending one that nobody declares is an error. */
  private sendersOf(
    contracts: readonly ServiceContract[],
    index: ContractIndex,
  ): Map<string, Set<string>> {
    const senders = new Map<string, Set<string>>();
    for (const contract of contracts) {
      for (const command of contract.sends) {
        if (!index.commands.has(command.type)) {
          throw ExportError.forTopology(
            `${contract.service} sends ${command.type}, which no contract declares`,
          );
        }
        const set = senders.get(command.type) ?? new Set<string>();
        set.add(contract.service);
        senders.set(command.type, set);
      }
    }
    return senders;
  }

  private topicOf({
    service,
    value: topic,
  }: Owned<TopicDefinition>): JsonObject {
    return {
      name: topic.name,
      fifo: topic.fifo,
      owner: service,
      producers: [service],
      description: topic.description,
    };
  }

  /** The queue producers are the services that send any of its commands. */
  private queueOf(
    { service, value: queue }: Owned<QueueDefinition>,
    index: ContractIndex,
    senders: ReadonlyMap<string, ReadonlySet<string>>,
  ): JsonObject {
    const producers = queue.commands.flatMap((command) => [
      ...(senders.get(command.type) ?? []),
    ]);
    return {
      name: queue.name,
      fifo: queue.fifo,
      visibilityTimeoutSeconds: queue.visibilityTimeoutSeconds,
      maxAttempts: queue.retry.maxAttempts,
      retry: {
        maxAttempts: queue.retry.maxAttempts,
        baseMs: queue.retry.baseMs,
        maxMs: queue.retry.maxMs,
      },
      dlq: {
        name: `${queue.name}${DEAD_LETTER_SUFFIX}`,
        maxReceiveCount: queue.deadLetter.maxReceiveCount,
        retentionSeconds: queue.deadLetter.retentionDays * SECONDS_PER_DAY,
      },
      subscriptions: this.subscriptionsOf(queue, index),
      consumer: service,
      producers: this.sorted(producers),
      description: queue.description,
    };
  }

  private subscriptionsOf(
    queue: QueueDefinition,
    index: ContractIndex,
  ): JsonObject[] {
    return queue.subscriptions
      .map((subscription) => {
        const owner = index.topics.get(subscription.topic.name);
        if (!owner) {
          throw ExportError.forTopology(
            `queue ${queue.name} subscribes to ${subscription.topic.name}, which no contract declares`,
          );
        }
        const published = new Set(owner.value.events.map((e) => e.type));
        const named = [...subscription.topic.events, ...subscription.events];
        for (const event of named) {
          if (!published.has(event.type)) {
            throw ExportError.forTopology(
              `queue ${queue.name} expects ${event.type} on ${subscription.topic.name}, but ${owner.service} does not publish it there`,
            );
          }
        }
        return {
          topic: subscription.topic.name,
          filterTypes: this.sorted(subscription.events.map((e) => e.type)),
        };
      })
      .sort((a, b) => this.compare(a.topic, b.topic));
  }

  private indexContracts(contracts: readonly ServiceContract[]): ContractIndex {
    const topics = new Map<string, Owned<TopicDefinition>>();
    const queues: Owned<QueueDefinition>[] = [];
    const commands = new Map<string, string>();
    for (const contract of contracts) {
      const { service } = contract;
      for (const topic of Object.values(contract.topics)) {
        topics.set(topic.name, { service, value: topic });
      }
      for (const queue of Object.values(contract.queues)) {
        queues.push({ service, value: queue });
      }
      for (const command of Object.values(contract.commands)) {
        commands.set(command.type, service);
      }
    }
    return { topics, queues, commands };
  }

  private byName(a: { name: string }, b: { name: string }): number {
    return this.compare(a.name, b.name);
  }

  /** Order by code unit, the same in any locale. */
  private compare(a: string, b: string): number {
    return a < b ? -1 : a > b ? 1 : 0;
  }

  private sorted(values: Iterable<string>): string[] {
    return [...new Set(values)].sort();
  }
}
